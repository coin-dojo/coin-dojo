#!/bin/bash
# HOST side (arm64 privileged container): mount the 3-partition image, bind the
# kernel fs, copy the offline cache, chroot in and run chroot-setup.sh, seed the
# /data skeleton, then cleanly unmount. Partition offsets are auto-detected.
# No secrets go into the root filesystem (#237). The first-boot config lands on the boot partition as
# coindojo.yml: /work/.coindojo.yml (CONFIG=, copied by run.sh), else one generated from COINDOJO_PASSWORD
# (hashed in the chroot, stdin only) and COINDOJO_PUBKEY (the Keychain flow), else none (first-boot hint).
# EDITION=community (the default) with no password in that config: the user gets the default login password 12345
# (#265, hashed in the chroot with a random salt; SSH stays key-only). EDITION=personal: the account stays locked.
# Opt-in COIN_DOJO_SSH_PASSWORD=yes.  Optional cache dir: /work/cache.
# This is the BASE; provision.sh then runs the cabinet's Ansible roles into the image (#244).
set -euo pipefail
export DEBIAN_FRONTEND=noninteractive
IMG=${1:?image}
command -v sfdisk >/dev/null || { apt-get update -qq >/dev/null && apt-get install -y -qq fdisk >/dev/null; }

part(){ sfdisk -d "$IMG" | awk -F'[=,]' -v n="$1" -v f="$2" '/ : start=/{c++; if(c==n){s=$2;z=$4;gsub(/ /,"",s);gsub(/ /,"",z); if(f=="start")print s; else print z; exit}}'; }
P1S=$(part 1 start); P1Z=$(part 1 size)
P2S=$(part 2 start); P2Z=$(part 2 size)
P3S=$(part 3 start); P3Z=$(part 3 size)
echo ">> parts: boot=$P1S/$P1Z root=$P2S/$P2Z data=$P3S/$P3Z"

cleanup(){ set +e
  umount /mnt/root/data 2>/dev/null
  umount /mnt/root/boot/firmware 2>/dev/null
  umount /mnt/root/dev/pts /mnt/root/dev /mnt/root/proc /mnt/root/sys 2>/dev/null
  umount /mnt/root 2>/dev/null
  for L in $RL $BL $DL; do [ -n "$L" ] && losetup -d "$L" 2>/dev/null; done
}
trap cleanup EXIT
RL=$(losetup --find --show --offset $((P2S*512)) --sizelimit $((P2Z*512)) "$IMG")
BL=$(losetup --find --show --offset $((P1S*512)) --sizelimit $((P1Z*512)) "$IMG")
DL=$(losetup --find --show --offset $((P3S*512)) --sizelimit $((P3Z*512)) "$IMG")

mkdir -p /mnt/root; mount "$RL" /mnt/root
mkdir -p /mnt/root/boot/firmware; mount "$BL" /mnt/root/boot/firmware
mount --bind /dev /mnt/root/dev; mount --bind /dev/pts /mnt/root/dev/pts
mount --bind /proc /mnt/root/proc; mount --bind /sys /mnt/root/sys
cp /etc/resolv.conf /mnt/root/etc/resolv.conf

# scripts + cache into the chroot
cp /work/chroot-setup.sh /mnt/root/root/chroot-setup.sh
cp /work/firstboot-expand.sh /mnt/root/tmp/firstboot-expand.sh
cp /work/wifi-import.sh /mnt/root/tmp/wifi-import.sh
cp /work/coindojo-firstboot.py /mnt/root/tmp/coindojo-firstboot.py
cp /work/coindojo.example.yml /mnt/root/tmp/coindojo.example.yml
chmod +x /mnt/root/root/chroot-setup.sh
[ -d /work/cache ] && { mkdir -p /mnt/root/tmp/cache; cp -r /work/cache/* /mnt/root/tmp/cache/ 2>/dev/null || true; }

# The chroot build gets no secrets at all (#237); settings travel as shell prefix assignments.
COIN_DOJO_SSH_PASSWORD="${COIN_DOJO_SSH_PASSWORD:-no}" \
  HK_CABINET_USER="${HK_CABINET_USER:-coindojo}" HK_CABINET_UID="${HK_CABINET_UID:-1000}" \
  HK_CABINET_HOSTNAME="${HK_CABINET_HOSTNAME:-coin-dojo}" chroot /mnt/root /bin/bash /root/chroot-setup.sh

# seed /data skeleton at build time (p3), so structure exists before firstboot
mkdir -p /mnt/root/data; mount "$DL" /mnt/root/data
# The per-system ROM folders are NOT typed here (#244): role `cores` makes one per system launch.py knows.
mkdir -p /mnt/root/data/roms /mnt/root/data/bios /mnt/root/data/saves /mnt/root/data/states /mnt/root/data/media
cat > /mnt/root/data/roms/README.txt <<'RM'
Drop your own legally-owned ROMs here, one folder per system (the folders are already made).
BIOS -> /data/bios :  naomi.zip, dc_boot.bin+dc_flash.bin, scph5501.bin
Neo Geo -> roms/neogeo : neogeo.zip goes here, next to the Neo Geo games.
(CPS1/2/3 and most console cores need no BIOS.)
Fightcade -> roms/fightcade : the versions Fightcade wants, when they differ from the game menu's (it looks there first).
This OS ships NO ROMs, BIOS, or artwork by design.
RM
# The image user's, by name (#244: Pi OS trixie has its own `pi` = uid 1000, so a numeric 1000 gave /data to pi).
chroot /mnt/root chown -R "${HK_CABINET_USER:-coindojo}:${HK_CABINET_USER:-coindojo}" /data
chroot /mnt/root chown root:root /data/lost+found

# ---- first-boot config onto the FAT boot partition (applied + scrubbed by coindojo-firstboot) ----
CFG=/mnt/root/boot/firmware/coindojo.yml
rm -f "$CFG"
if [ -f /work/.coindojo.yml ]; then
  cp /work/.coindojo.yml "$CFG"; echo ">> first-boot config: CONFIG= file"
elif [ -n "${COINDOJO_PASSWORD:-}${COINDOJO_PUBKEY:-}" ]; then
  {
    echo "# Generated by make image (personal flow). Applied once at first boot, then removed."
    echo "user: ${HK_CABINET_USER:-coindojo}"
    if [ -n "${COINDOJO_PASSWORD:-}" ]; then
      # The password reaches openssl on stdin, never as an argv word (#42 MED-5); only its hash is written.
      H=$(printf '%s' "$COINDOJO_PASSWORD" | chroot /mnt/root openssl passwd -6 -stdin)
      echo "password_hash: '$H'"
    fi
    [ -z "${COINDOJO_PUBKEY:-}" ] || printf 'ssh_pubkey: "%s"\n' "$COINDOJO_PUBKEY"
  } > "$CFG"
  echo ">> first-boot config: generated (password hash + SSH key)"
else
  echo ">> first-boot config: none (the cabinet shows the no-config hint; add coindojo.yml to the boot partition)"
fi
if [ -f "$CFG" ]; then
  # Checked in place on the boot partition: no copy ever touches the root filesystem.
  chroot /mnt/root /usr/bin/python3 /usr/local/sbin/coindojo-firstboot --check /boot/firmware/coindojo.yml --user "${HK_CABINET_USER:-coindojo}" \
    || { rm -f "$CFG"; echo "ERROR: the first-boot config is malformed or names another user (the line above says why)" >&2; exit 1; }
fi
# ---- the community image's default login (#265): <user> / 12345 when that config sets no password ----
# coindojo-firstboot hashes it with `openssl passwd -6` (a new random salt every build, no committed hash), sets it
# with chpasswd -e and keeps the hash in /etc/coindojo/default-password, so every boot can say "change it with
# passwd" until it is changed. #270: it also takes the user out of the sudo group (admin comes only from a
# boot-partition password at boot: coindojo.yml password_hash / prompt, Imager userconf.txt). EDITION=personal, or a password_hash:/password: prompt in the config: nothing.
chroot /mnt/root /usr/bin/python3 /usr/local/sbin/coindojo-firstboot --default-login --user "${HK_CABINET_USER:-coindojo}" \
  --edition "${EDITION:-community}" --config /boot/firmware/coindojo.yml \
  || { echo "ERROR: the default login could not be set (the line above says why)" >&2; exit 1; }

rm -f /mnt/root/root/chroot-setup.sh /mnt/root/tmp/firstboot-expand.sh /mnt/root/tmp/wifi-import.sh \
  /mnt/root/tmp/coindojo-firstboot.py /mnt/root/tmp/coindojo.example.yml
rm -rf /mnt/root/tmp/cache
echo "HOST_BUILD_DONE"
