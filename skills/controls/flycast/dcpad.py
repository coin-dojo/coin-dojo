#!/usr/bin/env python3
"""Dreamcast per-game stick mode for standalone flycast 2.7 (the maintainer 2026-11-15: Ikaruga does not move).

Why: the panel stick reports only ABS_X/ABS_Y (no hat), so with `SDL_USB gamepad.cfg` it drives the DC ANALOG stick.
Games whose disc says they do not need an analog stick (IP.BIN peripheral bits 21/22 clear, i.e. they must work with
the official, digital DC Arcade Stick) read the D-PAD, and some (Ikaruga) read only the d-pad. flycast maps one axis
direction to exactly one DC key, so the stick cannot drive both: per game we choose d-pad or analog.

  ipbin <file.chd|track.bin> ...  print game ID, peripheral field and decoded flags (CHD needs chdman, laptop only)
  render <base.cfg> <GAME_ID>      print the per-game mapping: base with axes 0/1 on the DC d-pad
  plan <dc_games.tsv>              per-game file name and mode for every row (dry run, nothing written)

flycast loads "SDL_<pad name>_<game ID>.cfg" before "SDL_<pad name>.cfg" (core/input/gamepad_device.cpp
make_mapping_filename / find_mapping, v2.7); the game ID is IP.BIN's product number, trailing blanks trimmed
(core/emulator.cpp loadGameSpecificSettings). Peripheral bits: Marcus Comstedt, mc.pp.se/dc/ip0000.bin.html.
"""
import os
import re
import shutil
import subprocess
import sys
import tempfile

PAD_NAME = "USB gamepad"
# IP.BIN peripheral field (7 hex digits at 0x38): bit -> name. Bits 12-24 = the disc's MINIMUM controller.
PERIPHERAL_BITS = {0: "wince", 4: "vga", 8: "other", 9: "purupuru", 10: "mic", 11: "vmu", 12: "start_a_b_dpad",
                   13: "c", 14: "d", 15: "x", 16: "y", 17: "z", 18: "dpad2", 19: "analog_r", 20: "analog_l",
                   21: "analog_h", 22: "analog_v", 23: "analog2_h", 24: "analog2_v", 25: "gun", 26: "keyboard",
                   27: "mouse"}
STICK_AXES = {"0-": "btn_analog_left", "0+": "btn_analog_right", "1-": "btn_analog_up", "1+": "btn_analog_down"}
DPAD_FOR_AXIS = {"0-": "btn_dpad1_left", "0+": "btn_dpad1_right", "1-": "btn_dpad1_up", "1+": "btn_dpad1_down"}
ID_RE = re.compile(r"^[A-Z0-9-]{3,10}$")


def parse_ip(sector):
    """First 2048 bytes of the GD-ROM high-density data track (IP.BIN) -> dict."""
    if sector[:16] != b"SEGA SEGAKATANA ":
        raise ValueError("not a Dreamcast IP.BIN (hardware id %r)" % sector[:16])
    periph = sector[0x38:0x3F].decode("ascii")
    if not re.fullmatch(r"[0-9A-Fa-f]{7}", periph):
        raise ValueError("bad peripheral field %r" % periph)
    gid = sector[0x40:0x4A].split(b"\0")[0].decode("ascii").rstrip()
    return {"id": gid, "peripherals": periph.upper(),
            "title": sector[0x80:0x100].split(b"\0")[0].decode("ascii", "replace").strip()}


def flags(periph):
    v = int(periph, 16)
    return {name for bit, name in PERIPHERAL_BITS.items() if v >> bit & 1}


def needs_analog(periph):
    """True when the disc requires an analog stick (so it does not promise to work on the digital DC Arcade Stick)."""
    return bool(flags(periph) & {"analog_h", "analog_v"})


def mapping_filename(game_id):
    if not ID_RE.match(game_id):
        raise ValueError("unsafe game id %r" % game_id)
    return "SDL_%s_%s.cfg" % (PAD_NAME, game_id)


def render(base_text, game_id, title=""):
    """The base mapping with the stick's four axis directions moved from the analog stick to the d-pad."""
    mapping_filename(game_id)
    out, n, sec = [], 0, ""
    for line in base_text.splitlines():
        if line.startswith("["):
            sec = line.strip()
        m = re.match(r"^(bind\d+) = ([0-9]+[+-]):(\w+)$", line)
        if sec == "[analog]" and m and m.group(2) in STICK_AXES:
            if m.group(3) != STICK_AXES[m.group(2)]:
                raise ValueError("base binds axis %s to %s, expected %s" % (m.group(2), m.group(3), STICK_AXES[m.group(2)]))
            line = "%s = %s:%s" % (m.group(1), m.group(2), DPAD_FOR_AXIS[m.group(2)])
            n += 1
        out.append(line)
    if n != 4:
        raise ValueError("base has %d of the 4 stick axis binds" % n)
    head = ["; coin-dojo: flycast 2.7 per-game mapping for game ID %s%s (generated by skills/controls/flycast/dcpad.py"
            % (game_id, " (%s)" % title if title else ""),
            "; render; do not edit). = SDL_USB gamepad.cfg with the panel stick (axes 0/1) on the DC D-PAD instead of the",
            "; analog stick: this disc needs no analog stick, so it reads the d-pad like the DC Arcade Stick. Delete = back",
            "; to SDL_USB gamepad.cfg for this game."]
    body = [l for l in out if not l.startswith(";")]
    while body and not body[0].strip():
        body.pop(0)
    return "\n".join(head + [""] + body) + "\n"


def read_table(path):
    rows = []
    with open(path, encoding="utf-8") as f:
        for n, line in enumerate(f, 1):
            if not line.strip() or line.startswith("#"):
                continue
            cols = line.rstrip("\n").split("\t")
            if len(cols) != 5:
                raise ValueError("%s:%d: %d columns, need 5 (id rom peripherals stick note)" % (path, n, len(cols)))
            gid, rom, periph, stick, note = cols
            mapping_filename(gid)
            if not re.fullmatch(r"[0-9A-F]{7}", periph):
                raise ValueError("%s:%d: bad peripherals %r" % (path, n, periph))
            if stick not in ("dpad", "analog"):
                raise ValueError("%s:%d: stick must be dpad or analog, not %r" % (path, n, stick))
            if stick == "dpad" and needs_analog(periph):
                raise ValueError("%s:%d: %s needs an analog stick (%s), d-pad mode would break it" % (path, n, rom, periph))
            rows.append({"id": gid, "rom": rom, "peripherals": periph, "stick": stick, "note": note})
    if len({r["id"] for r in rows}) != len(rows):
        raise ValueError("%s: duplicate game id" % path)
    return rows


def _ip_from_file(path):
    if not path.endswith(".chd"):
        with open(path, "rb") as f:
            raw = f.read(4704)
        return parse_ip(raw[16:2064] if raw[:12] == b"\0" + b"\xff" * 10 + b"\0" else raw[:2048])
    chdman = shutil.which("chdman")
    if not chdman:
        raise SystemExit("chdman not found (brew install rom-tools)")
    with tempfile.TemporaryDirectory() as d:
        gdi = os.path.join(d, "x.gdi")
        subprocess.run([chdman, "extractcd", "-i", path, "-o", gdi, "-f"], check=True, capture_output=True)
        with open(gdi) as f:
            rows = [l.split() for l in f.read().splitlines()[1:] if l.strip()]
        track = next(r for r in rows if int(r[1]) >= 45000 and r[2] == "4")       # first high-density data track
        return _ip_from_file(os.path.join(d, track[4]))


def main(argv):
    if len(argv) >= 2 and argv[0] == "ipbin":
        for p in argv[1:]:
            ip = _ip_from_file(p)
            print("%s\t%s\t%s\tneeds_analog=%s\t%s\t%s" % (ip["id"], ip["peripherals"], os.path.basename(p),
                  needs_analog(ip["peripherals"]), ",".join(sorted(flags(ip["peripherals"]))), ip["title"]))
        return 0
    if len(argv) == 3 and argv[0] == "render":
        with open(argv[1], encoding="utf-8") as f:
            sys.stdout.write(render(f.read(), argv[2]))
        return 0
    if len(argv) == 2 and argv[0] == "plan":
        for r in read_table(argv[1]):
            print("%-8s %-6s %s" % (r["id"], r["stick"], mapping_filename(r["id"]) if r["stick"] == "dpad" else "(base)"))
        return 0
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
